#!/usr/bin/env python3
"""Generate the table of service keywords ay's macro handlers mention.

The macro audit refuses an UPPER_CASE argument of an unmodelled macro unless some
handler in the Go sources spells it as a "..." literal. The literals used to be
mined at run time from the Go sources embedded into the binary; this script
mines them at build time instead and emits a sorted []string.
"""

import argparse
import re
import sys

LITERAL = re.compile(rb'"([A-Z0-9_]+)"')


def looks_like_service_word(word: bytes) -> bool:
    return any(b"A" <= bytes([c]) <= b"Z" for c in word)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True)
    parser.add_argument("sources", nargs="+")
    args = parser.parse_args()

    tokens = set()
    for path in args.sources:
        with open(path, "rb") as stream:
            for match in LITERAL.finditer(stream.read()):
                word = match.group(1)
                if looks_like_service_word(word):
                    tokens.add(word.decode())

    lines = ["// Code generated by dev/gen_service_tokens.py; DO NOT EDIT.", "", "package main", "",
             "var knownServiceTokenList = [...]string{"]
    lines.extend(f"\t{token!r}," .replace("'", '"') for token in sorted(tokens))
    lines.append("}")
    lines.append("")

    with open(args.out, "w") as stream:
        stream.write("\n".join(lines))

    return 0


if __name__ == "__main__":
    sys.exit(main())
