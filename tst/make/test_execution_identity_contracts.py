import json
import unittest

from tst.make import test_exec_make as execution


class ExecutionIdentityContractsTest(unittest.TestCase):
    def test_identical_host_and_target_actions_execute_once(self):
        files = {'tool/ya.make': execution.program('tool', ['main.cpp']),
                 'tool/main.cpp': 'int main(){}\n',
                 'app/ya.make': execution.library([], 'RUN_PROGRAM(tool -o result.cpp input.txt IN input.txt OUT result.cpp)\n'),
                 'app/input.txt': 'hello\n'}
        ws = execution.Workspace(self, files)
        ws.write('ya.conf', '[flags]\nOPENSOURCE = "yes"\n[host_platform_flags]\nOPENSOURCE = "yes"\nFORCE_NO_PIC = "yes"\n')
        flags = ('-r', '-DNO_DEBUGINFO=yes', '--target-platform', 'default-linux-x86_64')
        graph = json.loads(ws.make('-G', '-j', '0', *flags, targets=('tool', 'app')).stdout)
        output = '$(B)/tool/main.cpp.o'
        compiles = [n for n in graph['graph'] if output in n['outputs']]
        self.assertEqual(len(compiles), 2)
        self.assertNotEqual(compiles[0]['uid'], compiles[1]['uid'])
        self.assertEqual({k: v for k, v in compiles[0].items() if k not in ('uid', 'self_uid')},
                         {k: v for k, v in compiles[1].items() if k not in ('uid', 'self_uid')})
        result = ws.make('-j', '1', *flags, targets=('tool', 'app'))
        self.assertEqual(execution.built_kinds(result.stderr).count(('CC', output)), 1)
        self.assertEqual(sum(output in json.loads(p.read_text()) for p in ws.uid_files()), 1)
        generated = json.loads(ws.meta_for('$(B)/app/result.cpp').read_text())['$(B)/app/result.cpp']['cas']
        self.assertIn('generated by tool', (ws.bld / 'cas' / generated[:2] / generated).read_text())
        self.assertEqual(execution.built_kinds(ws.make('-j', '1', *flags, targets=('tool', 'app')).stderr), [])

    def test_unparsed_input_after_large_directory_scan_keeps_its_content_identity(self):
        payload = 'opaque source payload\n' + 'x' * ((1 << 20) + 17)
        changed_payload = payload[:-1] + 'y'
        files = {
            'app/ya.make': 'UNION()\nSRCDIR(payload)\nCOPY_FILE(input.bin copied.bin)\nEND()\n',
            'payload/input.bin': payload,
            **{f'payload/marker_{i}': '' for i in range(4096)},
            'build/scripts/fs_tools.py': 'import shutil,sys\nassert sys.argv[1] == "copy"\nshutil.copyfile(sys.argv[2], sys.argv[3])\n',
        }
        ws = execution.Workspace(self, files)
        targets = ('build/platform/python/ymake_python3', 'app')
        environment = ws.env(AY_CHAOS='intern-shuffle=0')
        result = ws.make('-j', '1', targets=targets, env=environment)
        self.assertIn(('CP', '$(B)/app/copied.bin'), execution.built_kinds(result.stderr))

        def copied_content():
            content = json.loads(ws.meta_for('$(B)/app/copied.bin').read_text())['$(B)/app/copied.bin']['cas']
            return (ws.bld / 'cas' / content[:2] / content).read_text()

        self.assertEqual(copied_content(), files['payload/input.bin'])
        cached = ws.make('-j', '1', targets=targets, env=environment)
        self.assertEqual(execution.built_kinds(cached.stderr), [])
        ws.write('payload/input.bin', changed_payload)
        rebuilt = ws.make('-j', '1', targets=targets, env=environment)
        self.assertIn(('CP', '$(B)/app/copied.bin'), execution.built_kinds(rebuilt.stderr))
        contents = [json.loads(p.read_text()) for p in ws.uid_files()]
        payloads = {row['$(B)/app/copied.bin']['cas'] for row in contents if '$(B)/app/copied.bin' in row}
        self.assertEqual(len(payloads), 2)
        self.assertIn(changed_payload, [(ws.bld / 'cas' / item[:2] / item).read_text() for item in payloads])


if __name__ == '__main__':
    unittest.main(verbosity=2)
