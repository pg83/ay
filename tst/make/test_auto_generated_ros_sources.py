from tst.make.lib import MakeTest, PROJECT


class AutoGeneratedRosSourcesTest(MakeTest):
    def test_auto_generated_ros_messages_keep_their_generator_dependency(self):
        self.write("ya.make", "ROS_LIBRARY(e2e)\nONLY_TAGS(CPP_ROS)\nRUN_PYTHON3(generate.py OUT Answer.msg)\nEND()\n")
        self.write("generate.py", 'from pathlib import Path\nPath("Answer.msg").write_text("int32 value\\n")\n')
        graph = self.graph()
        source = self.node(graph, "Answer.msg")
        generated = self.node(graph, "Answer.h")
        self.assertIn(f"$(B)/{PROJECT}/Answer.msg", generated["inputs"])
        self.assertIn(source["uid"], generated["deps"])
