from tst.make.lib import MakeTest, PROJECT


class AutoGeneratedGazetteersTest(MakeTest):
    def test_python_only_modules_keep_generated_gazetteer_resources(self):
        self.write("ya.make", "PROTO_LIBRARY()\nONLY_TAGS(PY3_PROTO)\nRUN_PYTHON3(generate.py OUT answer.gztproto)\nRESOURCE(answer.gztproto /schema)\nEND()\n")
        self.write("generate.py", 'from pathlib import Path\nPath("answer.gztproto").write_text("package e2e; message Answer {}\\n")\n')
        graph = self.graph()
        generated = self.node(graph, "answer.gztproto")
        resources = [node for node in graph["graph"] if f"$(B)/{PROJECT}/answer.gztproto" in node["inputs"] and any("/objcopy_" in output for output in node["outputs"])]
        self.assertEqual(len(resources), 1)
        self.assertIn(generated["uid"], resources[0]["deps"])
