from tst.make.lib import MakeTest, PROJECT


class AutoGeneratedPythonTwoProtosTest(MakeTest):
    def test_auto_generated_protos_keep_native_codegen_in_python_two_variants(self):
        self.write("ya.make", f"PY2_PROGRAM(answer)\nPY_SRCS(MAIN main.py)\nPEERDIR({PROJECT}/schema)\nEND()\n")
        self.write("main.py", "print(42)\n")
        self.write("schema/ya.make", "PROTO_LIBRARY()\nONLY_TAGS(PY_PROTO)\nRUN_PYTHON3(generate.py OUT answer.proto)\nEND()\n")
        self.write("schema/generate.py", 'from pathlib import Path\nPath("answer.proto").write_text("syntax = \\\"proto2\\\"; message Answer {}")\n')
        graph = self.graph()
        proto = self.node(graph, "schema/answer.proto")
        generated = self.node(graph, "schema/answer.pb.cc")
        self.assertIn(proto["uid"], generated["deps"])
        compiled = self.node(graph, "schema/answer.pb.cc.py2.o")
        self.assertIn(generated["uid"], compiled["deps"])
